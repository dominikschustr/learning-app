import {
  Award,
  BookOpen,
  Bookmark,
  Brain,
  CalendarCheck,
  Crown,
  FileCheck,
  Flame,
  Highlighter,
  Footprints,
  Gem,
  Gift,
  Layers,
  Medal,
  Mountain,
  Rocket,
  Sparkles,
  Star,
  Swords,
  Target,
  Timer,
  TrendingUp,
  Trophy,
  Waves,
  Zap,
  type LucideProps,
} from "lucide-react";

const ICONS = {
  award: Award,
  "book-open": BookOpen,
  bookmark: Bookmark,
  brain: Brain,
  "calendar-check": CalendarCheck,
  crown: Crown,
  "file-check": FileCheck,
  flame: Flame,
  highlighter: Highlighter,
  footprints: Footprints,
  gem: Gem,
  gift: Gift,
  layers: Layers,
  medal: Medal,
  mountain: Mountain,
  rocket: Rocket,
  star: Star,
  swords: Swords,
  target: Target,
  timer: Timer,
  "trending-up": TrendingUp,
  trophy: Trophy,
  waves: Waves,
  zap: Zap,
} as const;

export function Icon({ name, ...props }: { name?: string } & LucideProps) {
  const Cmp = (name && ICONS[name as keyof typeof ICONS]) || Sparkles;
  return <Cmp {...props} />;
}
